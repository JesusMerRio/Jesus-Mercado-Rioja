let currentGallery = 0;
let currentImage = 0;


/* =========================================
   ABRIR GALERÍA
========================================= */

function openGallery(galleryIndex) {

    currentGallery = galleryIndex;

    currentImage = 0;

    updateGallery();

    const gallery =
        document.getElementById("gallery");

    gallery.classList.add("active");

    document.body.style.overflow = "hidden";
}


/* =========================================
   CERRAR GALERÍA
========================================= */

function closeGallery() {

    const gallery =
        document.getElementById("gallery");

    gallery.classList.remove("active");

    document.body.style.overflow = "";
}


/* =========================================
   ACTUALIZAR GALERÍA
========================================= */

function updateGallery() {

    const gallery =
        galleries[currentGallery];


    const imageElement =
        document.getElementById("gallery-image");

    const titleElement =
        document.getElementById("gallery-title");

    const captionElement =
        document.getElementById("gallery-caption");

    const counterElement =
        document.getElementById("gallery-counter");


    /*
        COMPROBAR SI EXISTE LA GALERÍA
    */

    if (!gallery) {

        return;
    }


    /*
        COMPROBAR SI HAY IMÁGENES
    */

    if (
        !gallery.images ||
        gallery.images.length === 0
    ) {

        imageElement.style.display = "none";

        titleElement.textContent =
            gallery.title || "";

        captionElement.textContent =
            "Sin imágenes";

        counterElement.textContent =
            "0 / 0";

        return;
    }


    /*
        OBTENER IMAGEN ACTUAL
    */

    const image =
        gallery.images[currentImage];


    /*
        MOSTRAR IMAGEN
    */

    imageElement.style.display = "block";

    imageElement.src =
        image.src;

    imageElement.alt =
        image.caption || gallery.title;


    /*
        TÍTULO DEL PROYECTO
    */

    titleElement.textContent =
        gallery.title;


    /*
        PIE DE FOTO
    */

    captionElement.textContent =
        image.caption || "";


    /*
        CONTADOR
    */

    counterElement.textContent =
        `${currentImage + 1} / ${gallery.images.length}`;
}


/* =========================================
   SIGUIENTE IMAGEN
========================================= */

function nextImage() {

    const gallery =
        galleries[currentGallery];


    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {

        return;
    }


    currentImage++;


    if (
        currentImage >=
        gallery.images.length
    ) {

        currentImage = 0;
    }


    updateGallery();
}


/* =========================================
   IMAGEN ANTERIOR
========================================= */

function previousImage() {

    const gallery =
        galleries[currentGallery];


    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {

        return;
    }


    currentImage--;


    if (currentImage < 0) {

        currentImage =
            gallery.images.length - 1;
    }


    updateGallery();
}


/* =========================================
   TECLADO
========================================= */

document.addEventListener(
    "keydown",
    function(event) {

        const gallery =
            document.getElementById("gallery");


        if (
            !gallery.classList.contains("active")
        ) {

            return;
        }


        if (
            event.key === "ArrowRight"
        ) {

            nextImage();
        }


        if (
            event.key === "ArrowLeft"
        ) {

            previousImage();
        }


        if (
            event.key === "Escape"
        ) {

            closeGallery();
        }

    }
);


/* =========================================
   CERRAR AL HACER CLICK FUERA
========================================= */

const galleryElement =
    document.getElementById("gallery");


galleryElement.addEventListener(
    "click",
    function(event) {


        /*
            Si pulsamos la imagen,
            NO cerramos.
        */

        if (
            event.target.closest("#gallery-image")
        ) {

            return;
        }


        /*
            Si pulsamos un botón,
            NO cerramos.
        */

        if (
            event.target.closest("button")
        ) {

            return;
        }


        /*
            Si pulsamos el contenido,
            NO cerramos.
        */

        if (
            event.target.closest(".gallery-content")
        ) {

            return;
        }


        /*
            Si llegamos aquí hemos
            pulsado el fondo negro.
        */

        closeGallery();

    }
);



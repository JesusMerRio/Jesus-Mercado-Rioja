/* =========================================
   VARIABLES
========================================= */

let currentGallery = 0;
let currentImage = 0;

let touchStartX = 0;
let touchStartY = 0;

const swipeMinDistance = 50;

let savedScrollPosition = 0;


/* =========================================
   ELEMENTOS
========================================= */

const galleryElement =
    document.getElementById("gallery");

const galleryImage =
    document.getElementById("gallery-image");

const galleryTitle =
    document.getElementById("gallery-title");

const galleryCaption =
    document.getElementById("gallery-caption");

const galleryCounter =
    document.getElementById("gallery-counter");

const galleryImageContainer =
    document.querySelector(".gallery-image-container");

const galleryClose =
    document.querySelector(".gallery-close");

const galleryPrev =
    document.querySelector(".gallery-prev");

const galleryNext =
    document.querySelector(".gallery-next");


/* =========================================
   ABRIR GALERÍA
========================================= */

function openGallery(galleryIndex) {

    if (
        galleryIndex < 0 ||
        galleryIndex >= galleries.length
    ) {
        console.error(
            "Galería inexistente:",
            galleryIndex
        );

        return;
    }

    if (!galleryElement) {
        console.error(
            "No existe el elemento #gallery."
        );

        return;
    }

    currentGallery = galleryIndex;

    currentImage = 0;

    updateGallery();

    savedScrollPosition =
        window.scrollY;

    galleryElement.classList.add("active");

    galleryElement.setAttribute(
        "aria-hidden",
        "false"
    );

    document.body.classList.add(
        "gallery-open"
    );

    document.body.style.top =
        `-${savedScrollPosition}px`;

    /*
       Ponemos el foco en el botón
       de cerrar para mejorar
       la navegación por teclado.
    */

    if (galleryClose) {
        galleryClose.focus();
    }
}


/* =========================================
   CERRAR GALERÍA
========================================= */

function closeGallery() {

    if (!galleryElement) {
        return;
    }

    galleryElement.classList.remove(
        "active"
    );

    galleryElement.setAttribute(
        "aria-hidden",
        "true"
    );

    document.body.classList.remove(
        "gallery-open"
    );

    document.body.style.top = "";

    window.scrollTo(
        0,
        savedScrollPosition
    );
}


/* =========================================
   ACTUALIZAR GALERÍA
========================================= */

function updateGallery() {

    const gallery =
        galleries[currentGallery];

    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {
        return;
    }

    if (
        currentImage < 0 ||
        currentImage >= gallery.images.length
    ) {
        currentImage = 0;
    }

    const image =
        gallery.images[currentImage];

    if (galleryImage) {

        galleryImage.src =
            image.src;

        galleryImage.alt =
            image.caption ||
            gallery.title;
    }

    if (galleryTitle) {

        galleryTitle.textContent =
            gallery.title;
    }

    if (galleryCaption) {

        galleryCaption.textContent =
            image.caption || "";
    }

    if (galleryCounter) {

        galleryCounter.textContent =
            `${currentImage + 1} / ${gallery.images.length}`;
    }
}


/* =========================================
   SIGUIENTE IMAGEN
========================================= */

function nextImage() {

    const gallery =
        galleries[currentGallery];

    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {
        return;
    }

    currentImage =
        (currentImage + 1) %
        gallery.images.length;

    updateGallery();
}


/* =========================================
   IMAGEN ANTERIOR
========================================= */

function previousImage() {

    const gallery =
        galleries[currentGallery];

    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {
        return;
    }

    currentImage =
        (
            currentImage -
            1 +
            gallery.images.length
        ) %
        gallery.images.length;

    updateGallery();
}


/* =========================================
   TECLADO
========================================= */

document.addEventListener(
    "keydown",
    function(event) {

        if (
            !galleryElement ||
            !galleryElement.classList.contains(
                "active"
            )
        ) {
            return;
        }

        if (event.key === "ArrowRight") {

            event.preventDefault();

            nextImage();
        }

        else if (event.key === "ArrowLeft") {

            event.preventDefault();

            previousImage();
        }

        else if (event.key === "Escape") {

            event.preventDefault();

            closeGallery();
        }
    }
);



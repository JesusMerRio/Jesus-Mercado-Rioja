/* =========================================
   VARIABLES
========================================= */

let currentGallery = 0;
let currentImage = 0;


/* =========================================
   VARIABLES PARA SWIPE
========================================= */

let touchStartX = 0;
let touchEndX = 0;

const swipeMinDistance = 50;


/* =========================================
   ABRIR GALERÍA
========================================= */

function openGallery(galleryIndex) {

    console.log("Abriendo galería:", galleryIndex);

    if (
        galleryIndex < 0 ||
        galleryIndex >= galleries.length
    ) {
        console.error(
            "Galería inexistente:",
            galleryIndex
        );

        return;
    }

    currentGallery = galleryIndex;
    currentImage = 0;

    const galleryElement =
        document.getElementById("gallery");

    if (!galleryElement) {
        console.error(
            "No existe el elemento #gallery"
        );

        return;
    }

    updateGallery();

    galleryElement.classList.add("active");

    document.body.style.overflow = "hidden";
}


/* =========================================
   CERRAR GALERÍA
========================================= */

function closeGallery() {

    const galleryElement =
        document.getElementById("gallery");

    if (!galleryElement) {
        return;
    }

    galleryElement.classList.remove("active");

    document.body.style.overflow = "";
}


/* =========================================
   ACTUALIZAR GALERÍA
========================================= */

function updateGallery() {

    const gallery =
        galleries[currentGallery];

    if (!gallery) {
        return;
    }

    const imageElement =
        document.getElementById("gallery-image");

    const titleElement =
        document.getElementById("gallery-title");

    const captionElement =
        document.getElementById("gallery-caption");

    const counterElement =
        document.getElementById("gallery-counter");


    if (
        !imageElement ||
        !titleElement ||
        !captionElement ||
        !counterElement
    ) {
        console.error(
            "Falta algún elemento del carrusel en el HTML."
        );

        return;
    }


    if (
        !gallery.images ||
        gallery.images.length === 0
    ) {

        imageElement.style.display = "none";

        titleElement.textContent =
            gallery.title;

        captionElement.textContent =
            "Sin imágenes";

        counterElement.textContent =
            "0 / 0";

        return;
    }


    if (
        currentImage < 0 ||
        currentImage >= gallery.images.length
    ) {

        currentImage = 0;
    }


    const image =
        gallery.images[currentImage];


    imageElement.style.display = "block";

    imageElement.src =
        image.src;

    imageElement.alt =
        image.caption || gallery.title;

    titleElement.textContent =
        gallery.title;

    captionElement.textContent =
        image.caption || "";

    counterElement.textContent =
        `${currentImage + 1} / ${gallery.images.length}`;
}


/* =========================================
   SIGUIENTE
========================================= */

function nextImage() {

    const gallery =
        galleries[currentGallery];

    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {
        return;
    }

    currentImage++;

    if (
        currentImage >=
        gallery.images.length
    ) {

        currentImage = 0;
    }

    updateGallery();
}


/* =========================================
   ANTERIOR
========================================= */

function previousImage() {

    const gallery =
        galleries[currentGallery];

    if (
        !gallery ||
        !gallery.images ||
        gallery.images.length === 0
    ) {
        return;
    }

    currentImage--;

    if (currentImage < 0) {

        currentImage =
            gallery.images.length - 1;
    }

    updateGallery();
}


/* =========================================
   TECLADO
========================================= */

document.addEventListener(
    "keydown",
    function(event) {

        const galleryElement =
            document.getElementById("gallery");

        if (
            !galleryElement ||
            !galleryElement.classList.contains("active")
        ) {
            return;
        }

        if (event.key === "ArrowRight") {
            nextImage();
        }

        if (event.key === "ArrowLeft") {
            previousImage();
        }

        if (event.key === "Escape") {
            closeGallery();
        }
    }
);


/* =========================================
   CERRAR AL PULSAR FONDO
========================================= */

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const galleryElement =
            document.getElementById("gallery");

        if (!galleryElement) {

            console.error(
                "No se encuentra #gallery en el HTML."
            );

            return;
        }


        galleryElement.addEventListener(
            "click",
            function(event) {

                if (
                    event.target.closest("button")
                ) {
                    return;
                }

                if (
                    event.target.closest(".gallery-content")
                ) {
                    return;
                }

                closeGallery();
            }
        );


        console.log(
            "Carrusel inicializado correctamente."
        );
    }
);


/* =========================================
   SWIPE — MÓVIL Y TABLET
========================================= */

document.addEventListener(
    "touchstart",
    function(event) {

        const galleryElement =
            document.getElementById("gallery");

        if (
            !galleryElement ||
            !galleryElement.classList.contains("active")
        ) {
            return;
        }

        touchStartX =
            event.changedTouches[0].screenX;
    },
    { passive: true }
);


document.addEventListener(
    "touchend",
    function(event) {

        const galleryElement =
            document.getElementById("gallery");

        if (
            !galleryElement ||
            !galleryElement.classList.contains("active")
        ) {
            return;
        }

        touchEndX =
            event.changedTouches[0].screenX;

        handleSwipe();
    },
    { passive: true }
);


/* =========================================
   PROCESAR SWIPE
========================================= */

function handleSwipe() {

    const distance =
        touchEndX - touchStartX;


    if (
        Math.abs(distance) <
        swipeMinDistance
    ) {
        return;
    }


    if (distance < 0) {

        nextImage();

    } else {

        previousImage();
    }
}


